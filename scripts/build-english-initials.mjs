/**
 * Rebuilds src/constants/englishInitialArt.ts, the drawings behind the English
 * opening initial: a hymn's first English letter, an Old English capital
 * written in UnifrakturMaguntia's pen (Coptic Vine Design, "English initials";
 * see assets/initials/english/README.txt).
 *
 * Run it after the artwork changes:  node scripts/build-english-initials.mjs
 *
 * Each of assets/initials/english/initial_A.svg ... initial_Z.svg is one path
 * (class "initial-letter"), drawn in one colour, in a viewBox as tall as every
 * other's -- the capitals 1440 units from y = -1440 to the baseline at 0, with
 * room for flourishes above and below -- and as wide as its own letter. Their
 * outlines are straight segments; they are written here in relative steps, to
 * a tenth of a unit, which the art draws the same at about two thirds the size.
 */
import { readFile, writeFile } from 'node:fs/promises';

const SOURCE = new URL('../assets/initials/english/', import.meta.url);
const OUTPUT = new URL('../src/constants/englishInitialArt.ts', import.meta.url);
const CAP_HEIGHT = 1440;

/** A tenth of a unit, written short. */
const number = (tenths) => String(tenths / 10);

/** An outline of absolute moves and lines (M, L, Z) in relative steps: each subpath from its absolute start, then l for each line. */
function relative(d) {
  const tokens = d.match(/[MLZmlz]|-?\d+(?:\.\d+)?/g);
  let out = '';
  let command = '';
  let x = 0;
  let y = 0;
  for (let i = 0; i < tokens.length; i += 1) {
    const token = tokens[i];
    if (/[MLZ]/i.test(token)) {
      command = token.toUpperCase();
      if (command === 'Z') out += 'z';
      continue;
    }
    // In tenths, rounded once, so the steps add up to the points exactly.
    const nx = Math.round(Number(token) * 10);
    const ny = Math.round(Number(tokens[i + 1]) * 10);
    i += 1;
    if (command === 'M') {
      out += `M${number(nx)} ${number(ny)}`;
      command = 'L';
    } else {
      out += `l${number(nx - x)} ${number(ny - y)}`.replace(/ -/g, '-');
    }
    x = nx;
    y = ny;
  }
  return out;
}

const initials = [];
let viewTop = null;
let viewHeight = null;
for (const letter of Array.from({ length: 26 }, (_, i) => String.fromCharCode(65 + i))) {
  const svg = await readFile(new URL(`initial_${letter}.svg`, SOURCE), 'utf8');
  const [x, top, width, height] = svg.match(/viewBox="([^"]+)"/)[1].split(/\s+/).map(Number);
  if (viewTop === null) [viewTop, viewHeight] = [top, height];
  if (top !== viewTop || height !== viewHeight) throw new Error(`initial_${letter}.svg is not on the others' scale`);
  const d = svg.match(/<path[^>]*class="initial-letter"[^>]*>/)?.[0].match(/\sd="([^"]+)"/)?.[1];
  if (!d) throw new Error(`initial_${letter}.svg has no initial-letter path`);
  initials.push({ letter, path: relative(d), viewBox: `${x} ${top} ${width} ${height}`, width });
}

await writeFile(OUTPUT, `/**
 * The English opening initials: Old English capitals written in
 * UnifrakturMaguntia's pen, one colour each. Generated by
 * scripts/build-english-initials.mjs from assets/initials/english -- edit the
 * artwork, not these strings.
 */

/** The capitals' height, from y = -${CAP_HEIGHT} to the baseline at 0, in the drawings' units. */
export const ENGLISH_INITIAL_CAP_HEIGHT = ${CAP_HEIGHT};
/** Every drawing's height, flourishes above and below included, and how far above the capitals it starts. */
export const ENGLISH_INITIAL_VIEW_HEIGHT = ${viewHeight};
export const ENGLISH_INITIAL_ABOVE_CAPS = ${-viewTop - CAP_HEIGHT};

export interface EnglishInitialArt {
  /** The letter, as an SVG path in its viewBox. */
  letter: string;
  /** Each letter's own width; all share the height. */
  viewBox: string;
  width: number;
}

export const ENGLISH_INITIALS: Record<string, EnglishInitialArt> = {
${initials.map(({ letter, path, viewBox, width }) => `  ${letter}: { letter: ${JSON.stringify(path)}, viewBox: '${viewBox}', width: ${width} },`).join('\n')}
};
`);
console.log(`Wrote ${initials.length} English initials (view height ${viewHeight}, ${-viewTop - CAP_HEIGHT} above the capitals).`);
