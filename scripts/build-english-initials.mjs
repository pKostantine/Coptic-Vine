/**
 * Rebuilds src/constants/englishInitialArt.ts, the drawings behind the English
 * opening initial: a hymn's first English letter set two lines tall in
 * Corinthia Bold (Coptic Vine Design, "Drop caps and decorated initials",
 * English and Arabic openings, option 3).
 *
 * Run it after the font changes:  node scripts/build-english-initials.mjs
 *
 * Each capital is kept as an SVG path in the font's own units, its origin on
 * the baseline at the start of its advance and y running down, with its
 * advance width and its bounds; the reader scales it to the text and sets it
 * beside the first two lines. Drawn rather than set in the font, it sits to
 * the point on every platform, stroke and shadow included.
 */
import { writeFile } from 'node:fs/promises';

import { advanceWidth, bounds, contourPath, glyphContours, glyphIndex, readFont } from './ttf-glyphs.mjs';

const FONT = new URL('../assets/fonts/Corinthia-Bold.ttf', import.meta.url);
const OUTPUT = new URL('../src/constants/englishInitialArt.ts', import.meta.url);

const font = await readFont(FONT);
const { data, tables, unitsPerEm } = font;
/** OS/2's cap height, in font units. */
const capHeight = data.readInt16BE(tables['OS/2'] + 88);

const place = (p) => ({ x: p.x, y: -p.y });
const initials = Array.from({ length: 26 }, (_, i) => String.fromCharCode(65 + i)).map((letter) => {
  const index = glyphIndex(font, letter.charCodeAt(0));
  const contours = glyphContours(font, index);
  const box = bounds(contours.flat());
  return {
    letter,
    path: contours.map((contour) => contourPath(contour, place)).join(''),
    advance: advanceWidth(font, index),
    ...box,
  };
});

await writeFile(OUTPUT, `/**
 * The English opening initials: Corinthia Bold's capitals as SVG paths, in the
 * font's units, each with its origin on the baseline at the start of its
 * advance and y running down. Generated by scripts/build-english-initials.mjs
 * -- edit the font, not these strings.
 */

export const ENGLISH_INITIAL_UNITS_PER_EM = ${unitsPerEm};
/** The capitals' height, as the font gives it (OS/2). */
export const ENGLISH_INITIAL_CAP_HEIGHT = ${capHeight};

export interface EnglishInitialGlyph {
  path: string;
  advance: number;
  xMin: number;
  yMin: number;
  xMax: number;
  yMax: number;
}

export const ENGLISH_INITIALS: Record<string, EnglishInitialGlyph> = {
${initials.map(({ letter, path, advance, xMin, yMin, xMax, yMax }) => `  ${letter}: { path: ${JSON.stringify(path)}, advance: ${advance}, xMin: ${xMin}, yMin: ${yMin}, xMax: ${xMax}, yMax: ${yMax} },`).join('\n')}
};
`);
console.log(`Wrote ${initials.length} English initials (cap height ${capHeight} of ${unitsPerEm}).`);
