/**
 * Rebuilds src/constants/englishInitialArt.ts, the drawings behind the English
 * opening initial: a hymn's first English letter, an Old English capital with
 * a rising vine (Coptic Vine Design, "English initials").
 *
 * Run it after the artwork changes:  node scripts/build-english-initials.mjs
 *
 * Each of assets/initials/english/initial_A.svg ... initial_Z.svg is a square
 * (viewBox 0 0 1000 1000) of two paths: the vine (class "initial-ornament")
 * and the capital ("initial-letter"), so each takes its own colour, as the
 * Coptic initials' do. Their outlines are straight segments; they are written
 * here in relative steps, which the art draws the same at about two thirds the
 * size.
 */
import { readFile, writeFile } from 'node:fs/promises';

const SOURCE = new URL('../assets/initials/english/', import.meta.url);
const OUTPUT = new URL('../src/constants/englishInitialArt.ts', import.meta.url);

function pathOf(svg, className) {
  const element = svg.match(new RegExp(`<path[^>]*class="${className}"[^>]*>`))?.[0];
  const d = element?.match(/\sd="([^"]+)"/)?.[1];
  if (!d) throw new Error(`No ${className} path`);
  return d;
}

/** An outline of absolute moves and lines (M, L, Z) in relative steps: each subpath from its absolute start, then l for each line. */
function relative(d) {
  const tokens = d.match(/[MLZmlz]|-?\d+(?:\.\d+)?/g);
  let out = '';
  let command = '';
  let x = 0;
  let y = 0;
  for (let i = 0; i < tokens.length; i += 1) {
    const token = tokens[i];
    if (/[MLZ]/i.test(token)) {
      command = token.toUpperCase();
      if (command === 'Z') out += 'z';
      continue;
    }
    const nx = Number(token);
    const ny = Number(tokens[i + 1]);
    i += 1;
    if (command === 'M') {
      out += `M${nx} ${ny}`;
      command = 'L';
    } else {
      out += `l${nx - x} ${ny - y}`.replace(/ -/g, '-');
    }
    x = nx;
    y = ny;
  }
  return out;
}

const initials = [];
for (const letter of Array.from({ length: 26 }, (_, i) => String.fromCharCode(65 + i))) {
  const svg = await readFile(new URL(`initial_${letter}.svg`, SOURCE), 'utf8');
  if (!svg.includes('viewBox="0 0 1000 1000"')) throw new Error(`initial_${letter}.svg is not the 1000 square`);
  initials.push({ letter, vine: relative(pathOf(svg, 'initial-ornament')), path: relative(pathOf(svg, 'initial-letter')) });
}

await writeFile(OUTPUT, `/**
 * The English opening initials: Old English capitals with a rising vine, each
 * a square of its vine and its letter, split so each takes its own colour as
 * the Coptic initials' do. Generated by scripts/build-english-initials.mjs
 * from assets/initials/english -- edit the artwork, not these strings.
 */

export const ENGLISH_INITIAL_VIEWBOX = '0 0 1000 1000';

export interface EnglishInitialArt {
  /** The vine, as an SVG path in ENGLISH_INITIAL_VIEWBOX. */
  vine: string;
  /** The capital. */
  letter: string;
}

export const ENGLISH_INITIALS: Record<string, EnglishInitialArt> = {
${initials.map(({ letter, vine, path }) => `  ${letter}: { vine: ${JSON.stringify(vine)}, letter: ${JSON.stringify(path)} },`).join('\n')}
};
`);
console.log(`Wrote ${initials.length} English initials.`);
