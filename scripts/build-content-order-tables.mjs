/**
 * Rebuilds src/constants/contentOrderTables.ts, every order table in the
 * content API's list, by name, with the schema it is in. A Subdocument,
 * Inline or Hyperlink row names the table it calls in full
 * (fractions.fractions) and the reader needs no list for it; one in capitals
 * (FRACTIONS), as offline books packed before 4 Nov 2026 have it, is found
 * here (utils/sentinelTables.js).
 *
 * Run it after the content Worker's table list changes:
 *   node scripts/build-content-order-tables.mjs
 * With --check it only says whether the file is current (tests/sentinelTables.test.cjs runs that).
 *
 * The list is workers/content-api/schema/content-tables.json's: an order table
 * is one whose rows are placements -- item_order, hymn_key and item_type --
 * rather than a schema's hymn_titles or hymn_texts.
 *
 * It also names the schemas whose reading_rules file their readings under the
 * Inline key that reads them (an inline_hymn_key column): the Procession of
 * the Cross's twelve stations, FIRST_GOSPEL and on.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SOURCE = new URL('../workers/content-api/schema/content-tables.json', import.meta.url);
const OUTPUT = new URL('../src/constants/contentOrderTables.ts', import.meta.url);
const ORDER_COLUMNS = ['item_order', 'hymn_key', 'item_type'];

/** The order tables in the content Worker's table list, [table, schema], by table name. */
export function contentOrderTables(contentTables) {
  const tables = contentTables.tables
    .filter((table) => {
      const columns = new Set(table.columns.map((column) => column.name));
      return ORDER_COLUMNS.every((name) => columns.has(name));
    })
    .map((table) => [table.table, table.schema])
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  // A name is the table's alone: the reader calls a table by its name only.
  const seen = new Map();
  for (const [table, schema] of tables) {
    if (seen.has(table)) throw new Error(`Two order tables are named ${table}: ${seen.get(table)}.${table} and ${schema}.${table}`);
    seen.set(table, schema);
  }
  return tables;
}

/** The schemas whose reading_rules file each reading under the Inline key that reads it. */
export function inlineReadingRuleSchemas(contentTables) {
  return contentTables.tables
    .filter((table) => table.table === 'reading_rules')
    .filter((table) => ['inline_hymn_key', 'reading_reference', 'sort_order'].every((name) => table.columns.some((column) => column.name === name)))
    .map((table) => table.schema)
    .sort();
}

export function renderContentOrderTables(contentTables) {
  const lines = contentOrderTables(contentTables).map(([table, schema]) => `  ${table}: '${schema}',`);
  const ruleSchemas = inlineReadingRuleSchemas(contentTables).map((schema) => `'${schema}'`).join(', ');
  return [
    '// Generated by scripts/build-content-order-tables.mjs from',
    '// workers/content-api/schema/content-tables.json. Do not edit by hand.',
    '',
    '/**',
    ' * Every order table in the content API\'s list, by name, with the schema it',
    ' * is in. A call names its table in full (fractions.fractions) and needs none',
    ' * of this; a call in capitals (FRACTIONS), as offline books packed before',
    ' * 4 Nov 2026 have it, is found here (utils/sentinelTables.js).',
    ' */',
    'export const CONTENT_ORDER_TABLES: Readonly<Record<string, string>> = Object.freeze({',
    ...lines,
    '});',
    '',
    '/**',
    " * The schemas whose reading_rules file each reading under the Inline key that",
    " * reads it (inline_hymn_key): the Procession of the Cross's stations, FIRST_GOSPEL",
    ' * and on (hymnLibrary.js, resolveInlineReadingRuleSection).',
    ' */',
    `export const INLINE_READING_RULE_SCHEMAS: readonly string[] = Object.freeze([${ruleSchemas}]);`,
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = renderContentOrderTables(JSON.parse(readFileSync(SOURCE, 'utf8')));
  if (process.argv.includes('--check')) {
    const current = readFileSync(OUTPUT, 'utf8');
    if (current !== text) {
      console.error('src/constants/contentOrderTables.ts is out of date. Run node scripts/build-content-order-tables.mjs.');
      process.exit(1);
    }
    console.log('src/constants/contentOrderTables.ts is up to date.');
  } else {
    writeFileSync(OUTPUT, text);
    console.log('src/constants/contentOrderTables.ts written.');
  }
}
